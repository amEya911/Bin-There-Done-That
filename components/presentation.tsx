"use client";
import { useEffect, useState } from "react";
import Link from "next/link";
import {
  ArrowUpRight,
  Camera,
  Check,
  Maximize,
  Upload,
  Radio,
} from "lucide-react";
import { api, scoped, imageData } from "@/lib/client";
import { Brand, ErrorNote } from "./ui";
export default function Presentation({ id }: { id: string }) {
  const [demo, setDemo] = useState<any>(null),
    [data, setData] = useState<any>(null),
    [photo, setPhoto] = useState("/images/overflow-bin-hamburg.jpg"),
    [custom, setCustom] = useState(false),
    [error, setError] = useState("");
  useEffect(() => {
    api(`/api/demo/sessions/${id}`)
      .then(setDemo)
      .catch((e) => setError(e.message));
    const load = () =>
      api(scoped("/api/dashboard?window=all", "demo:" + id))
        .then(setData)
        .catch((e) => setError(e.message));
    load();
    const t = setInterval(load, 2500);
    return () => clearInterval(t);
  }, [id]);
  return (
    <div className="presentation">
      <header>
        <Brand light />
        <span className="pill">ISOLATED CAMERA DEMO</span>
        <Link href={`/demo/${id}/dashboard`}>
          Open dashboard <ArrowUpRight size={16} />
        </Link>
        <button
          className="icon-button"
          aria-label="Enter full screen"
          onClick={() => document.documentElement.requestFullscreen?.()}
        >
          <Maximize size={18} />
        </button>
      </header>
      {error && <ErrorNote>{error}</ErrorNote>}
      <div className="presentation-layout">
        <section className="projector-image">
          <img
            src={photo}
            alt="Reference photograph of a visibly overflowing public street bin"
          />
          <div className="projector-caption">
            {custom
              ? "User-selected reference photo · Camera recognition test"
              : "Demo image · Hamburg, 2005 · Camera recognition test"}
          </div>
        </section>
        <aside>
          <span className="eyebrow">POINT YOUR PHONE AT THE PHOTO</span>
          <h1>
            Notice it.
            <br />
            Report it.
            <br />
            <span className="serif">Together.</span>
          </h1>
          <p>
            This photo is a recognition test. The session links it to a selected
            Toronto asset for demonstration.
          </p>
          <div className="presentation-bin">
            <span className="eyebrow">DEMO ASSET</span>
            <strong>{demo?.bin?.name || "Loading selected asset…"}</strong>
            <span>{demo?.bin?.sourceId}</span>
          </div>
          <div className="presentation-stats">
            <div>
              <strong>{data?.totalReports ?? "—"}</strong>
              <span>accepted reports</span>
            </div>
            <div>
              <strong>{data?.affectedBins ?? "—"}</strong>
              <span>affected bin</span>
            </div>
          </div>
          <div className="presentation-live" aria-live="polite">
            {data?.totalReports > 0 ? (
              <>
                <Check size={21} />
                <span>Report saved in the demo dashboard.</span>
              </>
            ) : (
              <>
                <Radio size={20} />
                <span>Waiting for fresh phone-camera observations…</span>
              </>
            )}
          </div>
          <label className="button outlined">
            <Upload size={15} />
            Choose another reference photo
            <input
              hidden
              type="file"
              accept="image/jpeg,image/png,image/webp"
              onChange={async (e) => {
                try {
                  if (e.target.files?.[0]) {
                    setPhoto(await imageData(e.target.files[0]));
                    setCustom(true);
                  }
                } catch (e) {
                  setError((e as Error).message);
                }
              }}
            />
          </label>
          <p className="small muted">
            Open the private scanner QR from Demo setup on your phone. No
            reports are generated by this screen.
          </p>
          {!custom && (
            <a
              className="image-credit"
              href="https://commons.wikimedia.org/wiki/File:Overflowing_Hamburg_street_garbage_bin.jpg"
              target="_blank"
              rel="noreferrer"
            >
              Photo: Alexander Marks, 2005 · Public domain{" "}
              <ArrowUpRight size={12} />
            </a>
          )}
        </aside>
      </div>
    </div>
  );
}
